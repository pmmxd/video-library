DEFAULT_MAX_KM = 60.0
UNKNOWN_CITY = "其他"

# 同一个 location 字符串没必要重复解析
_CACHE: dict[str, str | None] = {}


def parse_location(value: object) -> tuple[float, float] | None:
    """把 ISO 6709 形式的 location 解析成经纬度，无效返回 None。"""
    if not value:
        return None
    match = _ISO6709.match(str(value).replace(" ", ""))
    if match is None:
        return None
    try:
        latitude = float(match.group(1))
        longitude = float(match.group(2))
    except ValueError:
        return None
    if abs(latitude) < 0.0001 and abs(longitude) < 0.0001:
        return None
    if not (-90.0 <= latitude <= 90.0 and -180.0 <= longitude <= 180.0):
        return None
    return latitude, longitude


def _distance_km(lat1: float, lon1: float, lat2: float, lon2: float) -> float:
    radius = 6371.0
    phi1 = math.radians(lat1)
    phi2 = math.radians(lat2)
    dphi = math.radians(lat2 - lat1)
    dlambda = math.radians(lon2 - lon1)
    a = math.sin(dphi / 2) ** 2 + math.cos(phi1) * math.cos(phi2) * math.sin(dlambda / 2) ** 2
    return 2 * radius * math.asin(math.sqrt(min(1.0, a)))


def nearest_city(latitude: float, longitude: float, max_km: float = DEFAULT_MAX_KM) -> str | None:
    """返回 max_km 内最近的城市名，都不在范围内返回 None。"""
    best_name: str | None = None
    best_distance = max_km
    for name, city_lat, city_lon in CITIES:
        distance = _distance_km(latitude, longitude, city_lat, city_lon)
        if distance <= best_distance:
            best_distance = distance
            best_name = name
    return best_name


def location_city(value: object, max_km: float = DEFAULT_MAX_KM) -> str:
    """把 location 元数据转成城市名；解析不了或离城市太远归到「其他」。"""
    key = "" if value is None else str(value)
    if key in _CACHE:
        cached = _CACHE[key]
        return cached if cached else UNKNOWN_CITY
    point = parse_location(value)
    city = nearest_city(point[0], point[1], max_km) if point else None
    _CACHE[key] = city
    return city if city else UNKNOWN_CITY


UNKNOWN_LOCATION = "未记录位置"


def location_label(value: object, max_km: float = DEFAULT_MAX_KM) -> str:
    """把 location 元数据转成可直接展示和筛选的城市名。"""
    place = location_city(value, max_km)
    return UNKNOWN_LOCATION if place == UNKNOWN_CITY else place
